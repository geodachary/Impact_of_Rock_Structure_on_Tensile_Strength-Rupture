"""Supplementary table and figure testing the G/Gc profile claims.

Mode-I dominance was inferred from the *shape* of the low-angle G/Gc profiles:
monotonic increase at low foliation angles, oscillation only at intermediate
angles. Shape claims are measurable, so this script measures them across all 14
specimens and writes the evidence out as supplementary material.

    python scripts/make_fig20_supplement.py

Writes
  outputs/tables/fig20_GGc_profile_metrics.csv    per-specimen measurements
  outputs/tables/fig20_GGc_band_summary.csv       band means, the low-vs-intermediate test
  manuscript/tables/table_S_fig20_GGc.txt         supplementary table
  manuscript/fig_S_GGc_monotonicity.pdf    supplementary figure (+ .png)
"""
